"use strict";

/**
 * StudyRequest
 *
 * Represents a study access request received from an external Data Portal.
 *
 * The external system provides the study identifier and the descriptive
 * request payload. The Consent Management Service generates its own
 * requestId and manages the request lifecycle.
 *
 * Lifecycle:
 * PENDING  -> the hospitals have not all answered yet
 * APPROVED -> every required hospital approved
 * REJECTED -> at least one hospital rejected
 * EXPIRED  -> the review deadline passed with pending decisions
 */
module.exports = (sequelize, DataTypes) => {
    const StudyRequest = sequelize.define(
        "StudyRequest",
        {
            id: {
                type: DataTypes.INTEGER,
                autoIncrement: true,
                primaryKey: true,
                allowNull: false,
            },

            /**
             * Identifier generated by the Consent Management Service.
             *
             * Example:
             * req_2026_0001
             */
            requestId: {
                type: DataTypes.STRING,
                allowNull: false,
                unique: true,
            },

            /**
             * Identifier of the study in the external system or Data Portal.
             *
             * Example:
             * study_2026_0001
             */
            studyId: {
                type: DataTypes.STRING,
                allowNull: false,
            },

            /**
             * Type of access request received by the component.
             *
             * The document currently distinguishes between requests for
             * aggregated data and applications involving personal-level data.
             */
            formType: {
                type: DataTypes.ENUM("DATA_REQUEST", "DATA_ACCESS_APPLICATION"),
                allowNull: false,
            },

            /**
             * Human-readable title of the study.
             *
             * Stored as a dedicated column because it is frequently displayed
             * in dashboards, notifications and review pages.
             */
            title: {
                type: DataTypes.STRING,
                allowNull: false,
            },

            /**
             * Language used for the submitted study.
             *
             * Expected format: ISO 639-1, for example "en", "it" or "es".
             */
            language: {
                type: DataTypes.STRING(2),
                allowNull: false,
            },

            /**
             * Current overall state of the request.
             *
             * The initial state is PENDING.
             */
            status: {
                type: DataTypes.ENUM(
                    "PENDING",
                    "APPROVED",
                    "REJECTED",
                    "EXPIRED",
                ),
                allowNull: false,
                defaultValue: "PENDING",
            },

            /**
             * dataPortal who submitted the study request.
             *
             * Relationship:
             * dataPortal 1 --- N StudyRequest
             */
            dataPortalId: {
                type: DataTypes.INTEGER,
                allowNull: false,
                references: {
                    model: "dataPortals",
                    key: "id",
                },
                onUpdate: "CASCADE",
                onDelete: "RESTRICT",
            },

            /**
             * Complete descriptive content received from the external system.
             *
             * It may contain:
             * - public_project_info
             * - applicant
             * - purpose_of_use
             * - extraction_criteria
             * - requested_data_owners
             * - acknowledgements
             * - additional_information
             *
             * Operational fields such as status, requestId and expiration dates
             * are stored separately and should not be managed inside this JSON.
             */
            requestPayload: {
                type: DataTypes.JSONB,
                allowNull: false,
            },

            /**
             * Algorithm used to produce the applicant's signature.
             *
             * This describes the signature operation, not merely the type
             * of public key registered for the dataPortal.
             *
             * Examples:
             * ES256
             * RS256
             * ECDSA_SHA256
             */
            signatureAlgorithm: {
                type: DataTypes.STRING,
                allowNull: false,
            },

            /**
             * Hash of the exact request payload that was signed.
             *
             * The backend should recalculate the hash from the canonical payload
             * before verifying the signature.
             */
            signedPayloadHash: {
                type: DataTypes.TEXT,
                allowNull: false,
            },

            /**
             * Digital signature received with the study request.
             */
            signatureValue: {
                type: DataTypes.TEXT,
                allowNull: false,
            },

            /**
             * Date and time at which the applicant signed the payload.
             */
            signedAt: {
                type: DataTypes.DATE,
                allowNull: false,
            },

            /**
             * Date and time at which the request was accepted by the
             * Consent Management Service.
             */
            submittedAt: {
                type: DataTypes.DATE,
                allowNull: false,
                defaultValue: DataTypes.NOW,
            },

            /**
             * Deadline by which all hospitals must provide their decisions.
             *
             * A background job will mark the request as EXPIRED if the deadline
             * is reached while one or more hospital decisions are still pending.
             */
            expiresAt: {
                type: DataTypes.DATE,
                allowNull: false,
            },

            /**
             * Date and time at which the request reached a final state.
             *
             * It remains null while the request is PENDING.
             */
            resolvedAt: {
                type: DataTypes.DATE,
                allowNull: true,
            },
        },
        {
            tableName: "study_requests",
            timestamps: true,

            indexes: [
                {
                    unique: true,
                    fields: ["requestId"],
                },
                {
                    fields: ["studyId"],
                },
                {
                    fields: ["dataPortalId"],
                },
                {
                    fields: ["status"],
                },
                {
                    fields: ["expiresAt"],
                },
            ],
        },
    );

    /**
     * Model associations.
     */
    StudyRequest.associate = (models) => {
        /**
         * The dataPortal who submitted the request.
         */
        StudyRequest.belongsTo(models.dataPortal, {
            foreignKey: "dataPortalId",
            as: "dataPortal",
        });

        /*
         * Add this association after HospitalDecision has been created:
         *
         * StudyRequest.hasMany(models.HospitalDecision, {
         *   foreignKey: "studyRequestId",
         *   as: "hospitalDecisions",
         * });
         */
    };

    return StudyRequest;
};
